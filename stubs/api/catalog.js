/**
 * Каталог направлений «Атлас».
 * Цены — ориентировочные, в рублях, за двухместный номер или на человека.
 * Данные используются демо-движком, когда GigaChat недоступен, и как
 * «земля» для промпта, чтобы модель не придумывала несуществующие отели.
 */

const spot = (title, description, type, area, duration, cost = 0) => ({
  title,
  description,
  type,
  area,
  duration,
  cost,
})

const hotel = (name, area, rating, reviews, tier, basePrice, tags, description) => ({
  id: name
    .toLowerCase()
    .replace(/[^a-zа-я0-9]+/gi, '-')
    .replace(/^-|-$/g, ''),
  name,
  area,
  rating,
  reviews,
  tier,
  basePrice,
  tags,
  description,
})

const country = (data) => ({
  ...data,
  cities: data.cities.map((city) => ({
    ...city,
    hotels: city.hotels.map((item) => (item.id ? item : hotel(...item))),
  })),
})

