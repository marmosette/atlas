const COUNTRY_BY_ID = new Map(COUNTRIES.map((item) => [item.id, item]))

const normalize = (value) =>
  String(value || '')
    .toLowerCase()
    .replace(/ё/g, 'е')
    .trim()

const findCountry = (value) => {
  const query = normalize(value)
  if (!query) return null
  return (
    COUNTRY_BY_ID.get(query) ||
    COUNTRIES.find((item) => normalize(item.name) === query) ||
    COUNTRIES.find((item) => normalize(item.name).startsWith(query)) ||
    COUNTRIES.find((item) => normalize(item.name).includes(query)) ||
    null
  )
}

const getFeaturedCountries = () =>
  ['georgia', 'italy', 'japan', 'turkey', 'spain', 'thailand', 'uzbekistan', 'portugal']
    .map((id) => COUNTRY_BY_ID.get(id))
    .filter(Boolean)

